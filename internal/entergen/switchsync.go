// SwitchSyncFrame m414 ["sync", 开关号×N]：空表零帧（nil）。
func SwitchSyncFrame(ids []int32) ([]byte, error) {
	if len(ids) == 0 {
		return nil, nil
	}
	values := make([]CustomValue, 0, len(ids)+1)
	values = append(values, CustomString("sync"))
	for _, id := range ids {
		values = append(values, CustomInt(id))
	}
	return CustomMessageFrame(serverCustomGameStep, values...)
}
